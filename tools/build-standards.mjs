/**
 * build-standards.mjs — generate the coverage board's data from the real code table.
 *
 *     node tools/build-standards.mjs
 *
 * Reads the frozen 664-code CCSS-M table that lives in the Jumpdrive brain, pulls the 6th- and
 * 7th-grade standards out of it, merges in whatever coverage we have recorded, and writes
 * `site/data/standards.js`.
 *
 * WHY A GENERATOR AND NOT A HAND-TYPED LIST: the board is a claim about official standards. If
 * anybody retypes 53 codes by hand, one of them will be wrong, and a wrong standard code on a
 * product is the exact thing the "honest or absent" doctrine exists to prevent. The codes come
 * from the table or they don't appear.
 *
 * WHY A .js FILE AND NOT .json: every page here must work when Scott double-clicks it from disk,
 * and fetch() is dead on file://. Data ships as a script global. A .json twin is written beside
 * it for tooling, but the site never reads that one.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");

// The brain is the source of truth for standards. This generator runs on Scott's machine and
// commits its output; Netlify never needs this path (the site's build command stays empty).
const TABLE = resolve(
  ROOT, "..", "Jumpdrive", "NCHO", "standards", "ccssm", "ccssm-codes.json");

// Coverage lives here, hand-maintained, keyed by code. Anything absent is "todo".
//   done  — a worked, gated problem exists and has shipped into the sample
//   wip   — being built right now
//   todo  — not started
const COVERAGE = resolve(HERE, "coverage.json");

if (!existsSync(TABLE)) {
  console.error(`Cannot find the CCSS-M table at:\n  ${TABLE}\n` +
    `Run  python build-table.py  in Jumpdrive/NCHO/standards/ccssm/ first.`);
  process.exit(2);
}

const table = JSON.parse(readFileSync(TABLE, "utf8"));
const coverage = existsSync(COVERAGE) ? JSON.parse(readFileSync(COVERAGE, "utf8")) : {};

const DOMAIN_NAMES = {
  RP: "Ratios & Proportional Relationships",
  NS: "The Number System",
  EE: "Expressions & Equations",
  G:  "Geometry",
  SP: "Statistics & Probability",
};

// A "standard" is the numbered one (7.RP.A.2). The lettered ones (7.RP.A.2a) are its parts and
// are folded in as sub-items rather than counted separately — otherwise the board's denominator
// disagrees with how a teacher counts, and the number stops meaning anything.
const isStandard = /^([67])\.([A-Z]+)\.([A-D])\.(\d+)$/;
const isPart     = /^([67])\.([A-Z]+)\.([A-D])\.(\d+)([a-h])$/;

const parts = {};
for (const rec of Object.values(table.codes)) {
  const m = rec.short.match(isPart);
  if (!m) continue;
  const parent = `${m[1]}.${m[2]}.${m[3]}.${m[4]}`;
  (parts[parent] ||= []).push({ code: rec.short, text: rec.text });
}

const rows = [];
for (const rec of Object.values(table.codes)) {
  const m = rec.short.match(isStandard);
  if (!m) continue;
  const [, grade, domain, cluster, num] = m;
  rows.push({
    code: rec.short,
    grade: Number(grade),
    domain,
    domainName: DOMAIN_NAMES[domain] || domain,
    cluster,
    num: Number(num),
    text: rec.text,
    parts: (parts[rec.short] || []).sort((a, b) => a.code.localeCompare(b.code)),
    status: coverage[rec.short]?.status || "todo",
    note: coverage[rec.short]?.note || "",
  });
}

rows.sort((a, b) =>
  a.grade - b.grade ||
  a.domain.localeCompare(b.domain) ||
  a.cluster.localeCompare(b.cluster) ||
  a.num - b.num);

const counts = { total: rows.length, done: 0, wip: 0, todo: 0 };
for (const r of rows) counts[r.status] = (counts[r.status] || 0) + 1;

const payload = {
  generated: new Date().toISOString().slice(0, 10),
  source: table.source,
  frozen: table.frozen,
  notice: table.required_notice,
  domainNames: DOMAIN_NAMES,
  counts,
  rows,
};

mkdirSync(resolve(ROOT, "site", "data"), { recursive: true });
writeFileSync(resolve(ROOT, "site", "data", "standards.js"),
  "// GENERATED by tools/build-standards.mjs — do not hand-edit.\n" +
  "// Codes come from the frozen CCSS-M table in the Jumpdrive brain.\n" +
  "window.MATH_STANDARDS = " + JSON.stringify(payload, null, 1) + ";\n", "utf8");
writeFileSync(resolve(ROOT, "site", "data", "standards.json"),
  JSON.stringify(payload, null, 1), "utf8");

console.log(`site/data/standards.js written`);
console.log(`  ${counts.total} standards — ${counts.done} done · ${counts.wip || 0} in progress · ${counts.todo || 0} to do`);
const byGrade = { 6: 0, 7: 0 };
for (const r of rows) byGrade[r.grade]++;
console.log(`  grade 6: ${byGrade[6]}   grade 7: ${byGrade[7]}`);
console.log(`  codes frozen ${table.frozen} from ${table.source}`);
